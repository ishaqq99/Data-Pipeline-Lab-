  COMMENT = 'Published contract for InfoSec reporting and downstream consumers (Tableau)';
CREATE SCHEMA IF NOT EXISTS VULN_MGMT_PROD.SCHEMACHANGE            WITH MANAGED ACCESS
  COMMENT = 'schemachange deployment history';
DROP SCHEMA IF EXISTS VULN_MGMT_PROD.PUBLIC;

